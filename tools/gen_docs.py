"""Regenerates the data-driven documentation from the tuning files.

    python tools/gen_docs.py

Writes docs/TECH_TREE.md and docs/CONFIG_REFERENCE.md from
config/tech_tree.json and config/game_config.json. Run it after editing either
file so the docs stay in sync.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = json.loads((ROOT / "config/game_config.json").read_text(encoding="utf-8"))
TECH = json.loads((ROOT / "config/tech_tree.json").read_text(encoding="utf-8"))
HEADER = "<!-- Generated by tools/gen_docs.py from the config files. Do not edit by hand. -->\n\n"


def item_name(k):
    return CFG["items"].get(k, {}).get("name", k)


def cost_text(cost):
    return ", ".join(f"{v} {item_name(k)}" for k, v in cost.items()) or "-"


def fmt_time(s):
    s = int(s)
    return f"{s // 60}m {s % 60:02d}s" if s >= 60 else f"{s}s"


def effect_text(e):
    stat = f"`{e['stat']}`"
    if e.get("op") == "mul":
        return f"{stat} ×{e['value']}"
    if e.get("op") == "set":
        return f"{stat} = {e['value']}"
    return f"{stat} {e['value']:+g}"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return "\n".join(out) + "\n"


# --- TECH_TREE.md ---------------------------------------------------------------

def tech_doc():
    nodes = TECH["nodes"]
    by_id = {n["id"]: n for n in nodes}
    md = [HEADER, "# Technology Tree\n\n"]
    md.append("Source: [`config/tech_tree.json`](../config/tech_tree.json). Every node lives in that one file; "
              "edit it to rebalance costs, times, prerequisites and effects, then run `python tools/gen_docs.py`.\n\n")
    md.append("## How research works\n\n"
              "1. The **Research Lab** module must be installed **and** enabled (Modules window, `U`).\n"
              "2. Prerequisites (`requires`) must be researched first.\n"
              "3. The `cost` items are taken from cargo when research **starts**.\n"
              "4. Research takes `time` seconds of game time. It pauses while the Lab is disabled or the ship has no energy, "
              "and the Lab draws extra energy while it runs (`modules.lab.research_energy_per_sec`).\n"
              "5. Cancelling refunds 50% of the cost.\n"
              "6. On completion, `effects` modify ship stats, `unlocks` make modules or recipes available, and `sets` "
              "changes global flags (the Ion Drive switches `engine_mode` to `energy`).\n\n")
    total_time = sum(n.get("time", 0) for n in nodes)
    md.append(f"**{len(nodes)} technologies** in **{len(TECH['branches'])} branches**; researching everything takes "
              f"{fmt_time(total_time)} of lab time.\n\n")

    md.append("## Dependency graph\n\n```mermaid\nflowchart LR\n")
    for br in TECH["branches"]:
        md.append(f"  subgraph {br['id']}[\"{br['name']}\"]\n")
        for n in sorted([n for n in nodes if n["branch"] == br["id"]], key=lambda n: n.get("tier", 1)):
            md.append(f"    {n['id']}[\"{n['name']}<br/>T{n.get('tier', 1)} · {fmt_time(n.get('time', 0))}\"]\n")
        md.append("  end\n")
    for n in nodes:
        for r in n.get("requires", []):
            md.append(f"  {r} --> {n['id']}\n")
    md.append("```\n\n")

    for br in TECH["branches"]:
        md.append(f"## {br['name']}\n\n")
        rows = []
        for n in sorted([n for n in nodes if n["branch"] == br["id"]], key=lambda n: (n.get("tier", 1), n["name"])):
            eff = [effect_text(e) for e in n.get("effects", [])]
            un = n.get("unlocks", {})
            eff += [f"Unlocks module **{CFG['modules'].get(m, {}).get('name', m)}**" for m in un.get("modules", [])]
            eff += [f"Unlocks recipe **{CFG['recipes'].get(r, {}).get('name', r)}**" for r in un.get("recipes", [])]
            if "sets" in n:
                eff += [f"Sets `{k}` = `{v}`" for k, v in n["sets"].items()]
            reqs = ", ".join(by_id[r]["name"] for r in n.get("requires", [])) or "-"
            rows.append([f"**{n['name']}**<br/>`{n['id']}`", n.get("tier", 1), cost_text(n.get("cost", {})),
                         fmt_time(n.get("time", 0)), reqs, "<br/>".join(eff) or "-"])
        md.append(table(["Technology", "Tier", "Cost", "Time", "Requires", "Effects"], rows) + "\n")

    md.append("## Total resources to research everything\n\n")
    totals = {}
    for n in nodes:
        for k, v in n.get("cost", {}).items():
            totals[k] = totals.get(k, 0) + v
    md.append(table(["Item", "Total"], [[item_name(k), v] for k, v in sorted(totals.items(), key=lambda kv: -kv[1])]))
    (ROOT / "docs/TECH_TREE.md").write_text("".join(md), encoding="utf-8")


# --- CONFIG_REFERENCE.md ----------------------------------------------------------

def config_doc():
    md = [HEADER, "# Configuration Reference (current values)\n\n",
          "Snapshot of the values in [`config/game_config.json`](../config/game_config.json). "
          "For what each section means and how to tune it, see [CONFIGURATION.md](CONFIGURATION.md).\n\n"]

    md.append("## Ship base stats (`ship`)\n\nThese are the values before technology and module effects.\n\n")
    md.append(table(["Stat", "Value"], [[f"`{k}`", v] for k, v in CFG["ship"].items()]) + "\n")

    md.append("## Items (`items`)\n\n")
    rows = []
    for k, it in CFG["items"].items():
        use = it.get("use")
        rows.append([f"`{k}`", it["name"], it["weight"], it["volume"], it["price"], it["size"],
                     f"+{use['amount']} {use['restore']}" if use else "-"])
    md.append(table(["Id", "Name", "Weight", "Volume", "Price", "Size", "Use"], rows) + "\n")
    md.append("`size: small` drops are picked up automatically by proximity collection; `large` drops need the tractor beam.\n\n")

    md.append("## Recipes (`recipes`)\n\n")
    md.append(table(["Id", "Name", "Inputs", "Outputs", "Module", "Available at start"],
                    [[f"`{k}`", r["name"], cost_text(r["inputs"]), cost_text(r["outputs"]), r.get("module", "-"), "yes" if r.get("starting") else "research"]
                     for k, r in CFG["recipes"].items()]) + "\n")

    md.append("## Modules (`modules`)\n\n")
    unlocked_by = {}
    for n in TECH["nodes"]:
        for m in n.get("unlocks", {}).get("modules", []):
            unlocked_by[m] = n["name"]
    md.append(table(["Id", "Name", "Energy/s", "Effects", "Unlocked by"],
                    [[f"`{k}`", m["name"], m.get("energy_per_sec", 0), "<br/>".join(effect_text(e) for e in m.get("effects", [])) or m.get("description", ""),
                      "start" if m.get("starting") else unlocked_by.get(k, "?")] for k, m in CFG["modules"].items()]) + "\n")
    md.append(f"Installed at start: {', '.join(CFG['starting_modules'])}. Slot count: `ship.module_slots`.\n\n")

    md.append("## Loot tables (`loot`)\n\n")
    rows = []
    for t, entries in CFG["loot"].items():
        rows.append([f"`{t}`", "<br/>".join(f"{item_name(e['item'])} {e['min']}-{e['max']} ({int(e.get('chance', 1) * 100)}%)" for e in entries)])
    md.append(table(["Table", "Drops (min-max, chance)"], rows) + "\n")
    md.append("Counts are multiplied by sector richness (distance from origin), `ship.salvage_yield`, and for asteroids by size.\n\n")

    md.append("## Derelicts (`derelicts`)\n\n")
    md.append(table(["Type", "Radius", "HP", "Loot table"], [[k, v["radius"], v["hp"], v["loot"]] for k, v in CFG["derelicts"].items()]) + "\n")

    md.append("## Stars (`bodies.star_types`)\n\n")
    md.append(table(["Class", "Radius", "Heat factor", "Surface gravity", "Temperature K", "Weight"],
                    [[k, v["radius"], v["heat_factor"], v["surface_gravity"], v["temperature"], v["weight"]] for k, v in CFG["bodies"]["star_types"].items()]) + "\n")
    md.append("## Planets (`bodies.planet_types`)\n\n")
    md.append(table(["Type", "Radius", "Surface gravity", "Weight", "Ring chance"],
                    [[k, v["radius"], v["surface_gravity"], v["weight"], v.get("ring_chance", 0)] for k, v in CFG["bodies"]["planet_types"].items()]) + "\n")

    md.append("## World spawn chances (`world.spawn`, per 4,000-unit chunk)\n\n")
    md.append(table(["Key", "Value"], [[f"`{k}`", v] for k, v in CFG["world"]["spawn"].items()]) + "\n")
    md.append("Chances for asteroid fields, derelicts and scrap are multiplied by the biome density "
              f"(core {CFG['world']['biome']['density']['core']}, normal {CFG['world']['biome']['density']['normal']}, rim {CFG['world']['biome']['density']['rim']}).\n\n")

    md.append("## Difficulty presets (`difficulty`)\n\n")
    md.append(table(["Id", "Name", "Consumption ×", "Damage ×", "Permadeath", "Start credits"],
                    [[k, d["name"], d["consumption_multiplier"], d["damage_multiplier"], d["permadeath"], d["start_credits"]] for k, d in CFG["difficulty"].items()]) + "\n")

    md.append("## Station economy (`station`)\n\n")
    md.append(table(["Key", "Value"], [[f"`{k}`", v] for k, v in CFG["station"].items()]) + "\n")

    md.append("## Achievements (`achievements`)\n\n")
    md.append(table(["Id", "Name", "Stat", "Threshold"], [[a["id"], a["name"], f"`{a['stat']}`", a["threshold"]] for a in CFG["achievements"]]) + "\n")

    md.append("## Input bindings (`input_bindings`)\n\n")
    md.append(table(["Action", "Bindings"], [[f"`{k}`", ", ".join(v)] for k, v in CFG["input_bindings"].items()]) + "\n")
    md.append("Key names follow Godot's `OS.find_keycode_from_string` (e.g. `W`, `Shift`, `F1`, `Escape`). "
              "Mouse: `MouseLeft`, `MouseRight`, `MouseMiddle`, `WheelUp`, `WheelDown`. Gamepad: `JoyButton:<n>`, `JoyAxis:<n>+` / `JoyAxis:<n>-`.\n")
    (ROOT / "docs/CONFIG_REFERENCE.md").write_text("".join(md), encoding="utf-8")


if __name__ == "__main__":
    tech_doc()
    config_doc()
    print("Wrote docs/TECH_TREE.md and docs/CONFIG_REFERENCE.md")
